/**
 * Bundles the leaderboard function (server/ + the sim it re-runs) into one file, api/leaderboard.js,
 * so Vercel deploys it with no module resolution of its own. Committed, and rebuilt by `npm run build`.
 */
import { build } from 'esbuild';

await build({
  entryPoints: ['server/api-entry.ts'],
  outfile: 'api/leaderboard.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'none',
  banner: { js: '// Generated by tools/build-api.mjs from server/ and src/sim. Do not edit.' },
  logLevel: 'warning',
});
console.log('api/leaderboard.js built');
